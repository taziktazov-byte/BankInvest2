def _c(doc, text, size=14, bold=False, before=0, after=0, space=1.0):
    """Строка по центру без отступа."""
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.line_spacing = space
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    D._runs(par, text, size=size, bold=bold)
    return par


def _l(doc, text, size=14, bold=False, space=1.0, before=0, after=0):
    """Строка по левому краю без отступа."""
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
    pf.line_spacing = space
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    D._runs(par, text, size=size, bold=bold)
    return par


def _r(doc, text, size=14, space=1.0, before=0):
    par = doc.add_paragraph()
    pf = par.paragraph_format
    pf.first_line_indent = Cm(0)
    pf.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pf.line_spacing = space
    pf.space_before = Pt(before)
    pf.space_after = Pt(0)
    D._runs(par, text, size=size)
    return par


def _blank(doc, n=1, space=1.0):
    for _ in range(n):
        par = doc.add_paragraph()
        par.paragraph_format.first_line_indent = Cm(0)
        par.paragraph_format.line_spacing = space
        par.paragraph_format.space_before = Pt(0)
        par.paragraph_format.space_after = Pt(0)


