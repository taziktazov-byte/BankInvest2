    D.p(doc, "Параметры подключения задаются переменными среды или файлом server\\.env "
             "в каталоге сервера. Минимально необходимо указать адрес сервера, имя базы "
             "данных, логин и пароль. Перечень параметров приведён в таблице 5.1.")
    D.caption_table(doc, "5.1", "Параметры подключения к базе данных")
    D.table(doc, ["Переменная", "Назначение", "Значение"], [
        ["MSSQL_SERVER", "Адрес сервера, при необходимости с портом",
         "localhost,1433"],
        ["MSSQL_DATABASE", "Имя базы данных", "BankInvest"],
        ["MSSQL_USER", "SQL-логин приложения", "bankinvest"],
        ["MSSQL_PASSWORD", "Пароль логина", "задаётся при создании логина"],
        ["MSSQL_INSTANCE", "Имя именованного экземпляра, если используется", "SQLEXPRESS"],
        ["MSSQL_ENCRYPT", "Требуется ли шифрование соединения", "false"],
        ["BANKINVEST_AUTO_SEED", "Заполнять ли пустую базу демо-данными", "1"],
    ], [4.5, 7.4, 4.6], size=11)
    D.p(doc, "Для проверки соединения выполните в каталоге server команду npm run "
             "db:check. Программа проверки выводит адрес сервера, состояние "
             "подключения, наличие всех 13 таблиц и обеих хранимых процедур. Если "
             "таблицы или процедуры не найдены, повторите шаг 5.6.")

    D.h2(doc, "5.8 Запуск сервера приложений")
    D.p(doc, "Сервер запускается первым: он обслуживает и веб-версию, и запросы "
             "настольного приложения. В каталоге server выполните установку зависимостей "
             "(один раз) и запуск:", indent=False)
    D.listing(doc, "cd server\nnpm install        :: один раз, ставит драйвер mssql\nnpm start")
    D.p(doc, "На Windows удобнее воспользоваться файлом start-server.bat в корне "
             "проекта. После запуска в консоли появятся адреса веб-версии "
             "(http://localhost:8787/) и программного интерфейса "
             "(http://localhost:8787/api), а также перечень демонстрационных учётных "
             "записей. Проверить работоспособность сервера можно, открыв в браузере "
             "адрес http://localhost:8787/api/ping — сервер вернёт ответ с признаком "
             "успешного подключения к базе данных.")
    D.p(doc, "Если сервер должен быть доступен с других компьютеров сети, разрешите "
             "входящие подключения к порту 8787 в брандмауэре Windows и открывайте "
             "веб-версию по адресу сервера, например http://192.168.1.10:8787/.")

    D.h2(doc, "5.9 Запуск настольного приложения")
    D.p(doc, "Настольное приложение запускается из корневого каталога проекта "
             "командой dotnet run либо открытием файла BankInvest.csproj в среде "
             "Visual Studio 2022. Приложение обращается к серверу по адресу, указанному "
             "в его настройках; по умолчанию это http://localhost:8787. Для работы на "
             "другом компьютере адрес сервера изменяется в файле настроек приложения.")
    D.p(doc, "Для одновременного запуска сервера, веб-версии и настольного приложения "
             "предусмотрен файл start-all.bat: он запускает сервер, дожидается его "
             "готовности, открывает веб-версию в браузере и затем запускает настольное "
             "приложение.")

