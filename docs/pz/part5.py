    _fig(doc, "screen_transactions.png", "5.8", "Журнал операций")
    D.p(doc, "Раздел «Инвест. проекты» (рисунок 5.9) предназначен для оценки "
             "инвестиционных проектов: сотрудник вводит ставку дисконтирования и "
             "денежные потоки, а система рассчитывает чистый приведённый доход, "
             "внутреннюю норму доходности, индекс рентабельности и срок окупаемости.")
    _fig(doc, "screen_projects.png", "5.9", "Оценка инвестиционных проектов")
    D.p(doc, "Раздел «Отчёты / Аналитика» (рисунок 5.10) формирует сводку за период: "
             "количество исполненных операций, доход банка в виде комиссий и перечень "
             "наиболее востребованных бумаг.")
    _fig(doc, "screen_reports.png", "5.10", "Отчёты и аналитика")

    D.h2(doc, "5.12 Работа клиента банка")
    D.p(doc, "Клиент видит только собственные данные. После входа открывается раздел "
             "«Мои активы» (рисунок 5.11) с тем же составом столбцов, что и у "
             "сотрудника, но без возможности выбрать другого клиента: доступ "
             "ограничивается на сервере.")
    _fig(doc, "screen_client_portfolio.png", "5.11", "Активы клиента банка")
    D.p(doc, "В разделе «Мои предложения» (рисунок 5.12) клиент видит выставленные им "
             "заявки и может отозвать любую из них, пока она не выкуплена. Рынок "
             "предложений (рисунок 5.13) показывает активные заявки других клиентов "
             "с ценой и отклонением от рыночной цены.")
    _fig(doc, "screen_offers.png", "5.12", "Предложения клиента на продажу")
    _fig(doc, "screen_client_home.png", "5.13", "Главная страница клиента банка")

    D.h2(doc, "5.13 Работа администратора")
    D.p(doc, "Администратор управляет учётными записями и просматривает журнал "
             "действий (рисунок 5.14). При создании учётной записи указываются "
             "организация, логин, пароль и роль; для роли клиента дополнительно "
             "выбирается клиент, к которому относится запись. Блокировка записи "
             "прекращает доступ, но сохраняет историю операций пользователя.")
    _fig(doc, "screen_admin.png", "5.14", "Управление учётными записями")
    D.p(doc, "Настольное приложение сотрудника (рисунок 5.15) предоставляет те же "
             "разделы, что и веб-версия, и работает с тем же сервером, поэтому данные "
             "в обоих клиентах совпадают.")
    _fig(doc, "screen_desktop.png", "5.15", "Настольное приложение сотрудника банка")

    D.h2(doc, "5.14 Примеры сообщений системы")
    D.p(doc, "При неверном логине или пароле система выводит сообщение «Неверный логин "
             "или пароль», не уточняя, какое из полей заполнено неверно, и записывает "
             "попытку входа в журнал действий. При попытке указать количество больше "
             "свободного остатка появляется сообщение «Недостаточно свободных бумаг», "
             "а поле количества подсвечивается. При превышении суммы целевых долей "
             "над 100 % выводится сообщение «Сумма целевых долей превышает 100 %».")
    D.p(doc, "Все сообщения об ошибках хранятся в словаре интерфейса и выводятся на "
             "том языке, который выбрал пользователь, поэтому одна и та же ошибка "
             "понятна и русскоязычному, и англоязычному сотруднику.")

    D.h2(doc, "5.15 Действия при сбоях")
    D.p(doc, "Если при запуске сервера появляется сообщение об ошибке подключения "
             "к базе данных, проверьте, запущена ли служба SQL Server, включён ли "
             "протокол TCP/IP и совпадают ли логин и пароль в переменных среды. Ошибка "
             "«Login failed» означает, что учётная запись SQL-логина не создана или "
             "не совпадает пароль; ошибка сокета — что протокол TCP/IP отключён или "
             "закрыт порт. Если не открывается веб-версия, убедитесь, что порт 8787 "
             "не занят другим приложением и разрешён в брандмауэре.")
    D.p(doc, "Для сохранения данных база резервируется штатными средствами SQL Server: "
             "в среде SQL Server Management Studio выполняется задача «Создать задачу "
             "резервного копирования», файл копии сохраняется в каталоге Backup. "
             "Восстановление выполняется обратной задачей «Восстановить базу данных» "
             "с указанием файла копии.")


