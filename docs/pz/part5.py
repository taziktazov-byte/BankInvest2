    D.p(doc, "Страница бумаги (рисунок 5.7) содержит график цены за выбранный период, "
             "сведения о выпуске и список предложений на покупку и продажу. Журнал "
             "операций (рисунок 5.8) позволяет отобрать сделки по клиенту, бумаге и "
             "периоду.")
