"""Глава 3 — разработка алгоритмов и их программная реализация."""
import os

import docbuild as D

HERE = os.path.dirname(os.path.abspath(__file__))
SHOTS = os.path.join(HERE, "shots")
ROOT = os.path.dirname(os.path.dirname(HERE))


def _src(*parts):
    """Читает фрагмент исходного кода проекта для листинга."""
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


def _fig(doc, name, number, title, width=16.5):
    D.figure(doc, os.path.join(SHOTS, name), number, title, width_cm=width)


def chapter3(doc):
    D.h1(doc, "3 Разработка алгоритмов и их программная реализация", page_break=True)

    D.p(doc, "Алгоритм — это пошаговая процедура, которая определяет набор инструкций, "
             "выполняемых в заданном порядке для получения результата. Для наглядного "
             "представления алгоритмов в работе использованы блок-схемы: начало и конец "
             "обозначаются эллипсами, действия — прямоугольниками, проверки условий — "
             "ромбами. Ниже приведены алгоритмы основных операций системы: покупки и "
             "продажи ценных бумаг, авторизации и двух операций администрирования.")

    # ------------------------------------------------------------------ 3.1
    D.h2(doc, "3.1 Алгоритм покупки ценных бумаг по предложению")
    D.p(doc, "Покупка бумаг — самая ответственная операция системы, так как она "
             "изменяет остатки на двух счетах депо и должна выполняться целиком. "
             "Алгоритм начинается с того, что пользователь выбирает выпуск бумаги и "
             "предложение конкретного продавца, после чего указывает количество. "
             "Сервер получает запрос и последовательно проверяет условия: предложение "
             "существует и активно, покупатель не является продавцом, количество "
             "положительно и не превышает остатка, у продавца на счёте достаточно бумаг.")
    _fig(doc, "fig_alg_buy.png", "3.1", "Схема алгоритма покупки ценной бумаги по предложению",
         width=13.0)
    D.p(doc, "Если хотя бы одна проверка не пройдена, транзакция откатывается, и "
             "пользователь получает сообщение об ошибке — данные остаются неизменными. "
             "Если проверки пройдены, бумаги списываются со счёта продавца и зачисляются "
             "покупателю, остаток предложения уменьшается, а в журнал записываются две "
             "сделки с одинаковой комиссией: для покупателя — покупка, для продавца — "
             "продажа. Завершается алгоритм записью действия в журнал AuditLog.")
    D.p(doc, "Реализация алгоритма сосредоточена в хранимой процедуре usp_BuyListing. "
             "Процедура захватывает строку предложения с блокировкой UPDLOCK, HOLDLOCK: "
             "это не позволяет второму покупателю прочитать тот же остаток и купить "
             "бумаги, которых уже нет. Каждая проверка завершается откатом транзакции "
             "и ошибкой с кодом ERR_*, а сервер приложений переводит код ошибки в "
             "понятное сообщение интерфейса. Полный текст процедуры приведён в "
             "приложении 1.")

    # ------------------------------------------------------------------ 3.2
    D.h2(doc, "3.2 Алгоритм выставления предложения о продаже")
    D.p(doc, "Продажа начинается с выбора бумаги из собственного портфеля. Система "
             "показывает только те позиции, которые можно продать: из количества бумаг "
             "на счёте вычитается количество, уже зарезервированное в активных "
             "предложениях клиента. Поэтому один и тот же пакет бумаг нельзя выставить "
             "дважды.")
    _fig(doc, "fig_alg_sell.png", "3.2",
         "Схема алгоритма выставления предложения о продаже", width=15.5)
    D.p(doc, "После выбора бумаги клиент указывает количество и цену. Проверяются "
             "положительность цены, наличие свободного остатка и права пользователя на "
             "счёт депо: клиент может продавать только со своего счёта, сотрудник — со "
             "счёта обслуживаемого клиента. При успешной проверке создаётся запись в "
             "таблице Listings со статусом «Активно», и предложение сразу становится "
             "видно другим клиентам на рынке. Отзыв предложения меняет статус на "
             "«Отозвано», при этом бумаги снова становятся доступны для продажи.")

    # ------------------------------------------------------------------ 3.3
    D.h2(doc, "3.3 Алгоритм авторизации пользователя")
    D.p(doc, "Авторизация определяет, какие данные увидит пользователь. Пользователь "
             "вводит идентификатор организации (УНП) или логин, а также пароль. Сервер "
             "вычисляет хеш пароля алгоритмом SHA-256 и ищет учётную запись с указанным "
             "логином и полученным хешем. Пароль в базе данных хранится только в виде "
             "хеша, поэтому даже администратор базы не может прочитать его.")
    _fig(doc, "fig_alg_auth.png", "3.3", "Схема алгоритма авторизации пользователя",
         width=14.0)
    D.p(doc, "Если учётная запись найдена и активна, сервер создаёт сеанс: генерирует "
             "случайный токен, записывает его в таблицу Sessions вместе с логином, ролью "
             "и идентификатором клиента. Токен возвращается клиенту и передаётся в "
             "заголовке каждого следующего запроса. При неверном логине или пароле "
             "попытка фиксируется в журнале действий, а пользователь получает сообщение "
             "«Неверный логин или пароль» без указания того, что именно неверно.")
    D.p(doc, "Разграничение прав выполняется при каждом запросе: сервер читает токен, "
             "находит сеанс в таблице Sessions и сравнивает роль с требуемой для операции. "
             "Обращение клиента к данным другого клиента прерывается, даже если такой "
             "запрос сформирован вручную. Пароль при входе хешируется, неудачная попытка "
             "фиксируется в журнале, а для сеанса создаётся случайный токен.")
    D.p(doc, "Функция авторизации на стороне сервера приведена в приложении 2: она "
             "проверяет пароль, создаёт сеанс и записывает результат входа в журнал "
             "действий.")

    # ------------------------------------------------------------------ 3.4
    D.h2(doc, "3.4 Алгоритм добавления нового пользователя")
    D.p(doc, "Учётные записи создаёт администратор. При добавлении пользователя "
             "указываются организация, логин, пароль и роль, а для роли клиента — "
             "ещё и клиент, к которому относится учётная запись. Алгоритм проверяет "
             "заполнение обязательных полей, длину пароля и уникальность логина в "
             "пределах организации.")
    _fig(doc, "fig_alg_adduser.png", "3.4", "Схема алгоритма добавления нового пользователя",
         width=15.5)
    D.p(doc, "Если логин уже занят, пользователю выводится соответствующее сообщение, "
             "а данные не сохраняются. Если проверки пройдены, пароль хешируется и "
             "запись добавляется в таблицу Users. Новый сотрудник сразу может войти в "
             "систему; заблокировать доступ можно, сняв признак IsActive, — при этом "
             "запись и история её операций сохраняются.")

    # ------------------------------------------------------------------ 3.5
    D.h2(doc, "3.5 Алгоритм добавления ценной бумаги в справочник")
    D.p(doc, "Справочник выпусков ведёт сотрудник банка. При добавлении бумаги "
             "указываются эмитент, тикер, наименование, вид и сегмент, номинал, объём "
             "выпуска, ставка и доля расходов. Система проверяет заполнение "
             "обязательных полей, уникальность тикера и положительность числовых "
             "значений: номинал, объём и цена не могут быть отрицательными или "
             "нулевыми.")
    _fig(doc, "fig_alg_addsec.png", "3.5",
         "Схема алгоритма добавления ценной бумаги в справочник", width=15.5)
    D.p(doc, "Новый выпуск создаётся в статусе «Черновик» и недоступен для торговли. "
             "После регистрации сотрудник переводит выпуск в статус «Зарегистрирован», "
             "а после размещения — в «Размещён»; только размещённый выпуск попадает в "
             "список предложений и участвует в расчёте стоимости портфеля.")

    # ------------------------------------------------------------------ 3.6
    D.h2(doc, "3.6 Алгоритмы расчёта стоимости портфеля и оценки проектов")
    D.p(doc, "Расчётные алгоритмы реализованы в серверной части и не зависят от того, "
             "какой клиент отправил запрос, поэтому настольное приложение и браузер "
             "получают одинаковые числа. Стоимость портфеля определяется как сумма "
             "стоимостей всех позиций:")
    D.formula(doc, D._mr("V = ") + D._nary("∑", "i=1", "n",
             D._sub(D._mr("q"), D._mr("i")) + D._mr(" · ") +
             D._sub(D._mr("p"), D._mr("i"))), "3.1")
    D.where(doc, [
        "V — текущая стоимость портфеля, BYN;",
        "q — количество бумаг i-го выпуска на счёте депо, шт.;",
        "p — текущая рыночная цена бумаги i-го выпуска, BYN;",
        "n — число позиций в портфеле.",
    ])
    D.p(doc, "Текущая доля каждой позиции показывает, какую часть портфеля она "
             "занимает, а сравнение с целевой долей даёт сумму, которую следует "
             "докупить или продать:")
    D.formula(doc, D._sub(D._mr("d"), D._mr("i")) + D._mr(" = ") +
             D._frac(D._sub(D._mr("q"), D._mr("i")) + D._mr(" · ") +
                     D._sub(D._mr("p"), D._mr("i")), D._mr("V")) +
             D._mr(" · 100 %"), "3.2")
    D.where(doc, [
        "d — текущая доля i-й позиции в портфеле, %;",
        "q, p, V — те же величины, что в формуле (3.1).",
    ])
    D.formula(doc, D._sub(D._mr("A"), D._mr("i")) + D._mr(" = ") +
             D._mr("V · ") +
             D._frac(D._sub(D._mr("t"), D._mr("i")), D._mr("100")) +
             D._mr(" − ") + D._sub(D._mr("q"), D._mr("i")) +
             D._mr(" · ") + D._sub(D._mr("p"), D._mr("i")), "3.3")
    D.where(doc, [
        "A — сумма к действию: положительное значение означает, что позицию "
        "следует докупить, отрицательное — продать, BYN;",
        "t — целевая доля i-й позиции, заданная клиентом, %.",
    ])
    D.p(doc, "Оценка инвестиционного проекта выполняется методом дисконтирования "
             "денежных потоков. Чистый приведённый доход равен разности "
             "дисконтированных поступлений и первоначальных вложений:")
    D.formula(doc, D._mr("NPV = ") + D._nary("∑", "k=1", "m",
             D._frac(D._sub(D._mr("CF"), D._mr("k")),
                     D._sup(D._paren(D._mr("1 + r")), D._mr("k")))) +
             D._mr(" − ") + D._sub(D._mr("I"), D._mr("0")), "3.4")
    D.where(doc, [
        "NPV — чистый приведённый доход проекта, BYN;",
        "CF — денежный поток k-го года, BYN;",
        "I — первоначальные вложения, BYN;",
        "r — ставка дисконтирования, доли единицы;",
        "m — срок проекта, лет.",
    ])
    D.p(doc, "Индекс рентабельности показывает, сколько дохода приходится на единицу "
             "вложений, а внутренняя норма доходности — это ставка, при которой "
             "чистый приведённый доход обращается в ноль:")
    D.formula(doc, D._mr("PI = ") + D._frac(
        D._nary("∑", "k=1", "m",
                D._frac(D._sub(D._mr("CF"), D._mr("k")),
                        D._sup(D._paren(D._mr("1 + r")), D._mr("k")))),
        D._sub(D._mr("I"), D._mr("0"))), "3.5")
    D.formula(doc, D._mr("NPV") + D._paren(D._mr("IRR")) + D._mr(" = 0"), "3.6")
    D.p(doc, "Таким образом, в третьем разделе разработаны алгоритмы покупки и продажи "
             "ценных бумаг, авторизации, добавления пользователей и выпусков, а также "
             "приведены расчётные формулы, по которым сервер вычисляет стоимость "
             "портфеля, целевые суммы и показатели инвестиционных проектов.")

    # ------------------------------------------------------------------ 3.7
    D.h2(doc, "3.7 Программная реализация интерфейса")
    D.p(doc, "Интерфейс системы реализован дважды — для настольного приложения и для "
             "браузера, но в обоих случаях он построен по одному принципу: слева "
             "расположено меню разделов, сверху — строка заголовка с наименованием "
             "раздела и сведениями о пользователе, в рабочей области — таблицы, "
             "кнопки операций и модальные окна для ввода данных.")
    D.p(doc, "Веб-приложение состоит из одного HTML-документа, таблицы стилей и "
             "программного модуля, который загружает данные с сервера и перерисовывает "
             "разделы без перезагрузки страницы. Такой подход позволяет менять раздел "
             "быстрее, чем при полной перезагрузке, и сохранять состояние фильтров. "
             "Обновление данных в реальном времени построено на потоке событий сервера: "
             "после исполнения сделки сервер отправляет уведомление, и открытые окна "
             "перерисовывают таблицы.")
    D.p(doc, "Настольное приложение на платформе Windows Forms обращается к тем же "
             "адресам REST API через класс Api.cs, который добавляет к запросу токен "
             "сеанса и переводит ответ сервера в объекты. Разделы главной формы, "
             "портфеля, журнала операций и отчётов используют общие элементы "
             "управления, поэтому внешний вид обоих клиентов совпадает.")
    D.p(doc, "Все тексты интерфейса вынесены в словарь сервера и доступны на русском, "
             "английском и белорусском языках. Клиент запрашивает словарь при входе и "
             "хранит выбранный язык в сеансе, поэтому после повторного входа интерфейс "
             "открывается на том же языке. Сообщения об ошибках также берутся из "
             "словаря: сервер возвращает ключ ошибки, а клиент подставляет текст на "
             "нужном языке — так одна и та же ошибка понятна всем пользователям.")
    D.p(doc, "Итог третьего раздела: разработаны и реализованы алгоритмы пяти основных "
             "операций, расчётные алгоритмы портфеля и оценки проектов, а также "
             "описана программная реализация интерфейса обоих клиентов.")
