def introduction(doc):
    h1(doc, "ВВЕДЕНИЕ")

    p(doc, "Банк, который обслуживает инвесторов, ведёт учёт клиентов, их счетов депо, "
           "выпусков ценных бумаг и сделок по ним. Инвестор приходит, чтобы купить акции или "
           "облигации, и хочет видеть, из чего состоит его портфель и какую долю занимает каждая "
           "бумага. Сотрудник банка обслуживает сразу много клиентов: заводит их в систему, "
           "ставит бумаги на счёт, продаёт и покупает по заявкам. Ответственный сотрудник "
           "отчитывается перед руководством о числе сделок и доходе банка в виде комиссий.")
    p(doc, "На практике эти сведения расходятся по нескольким местам. Клиенты учитываются в "
           "одной таблице, портфели — в другой, заявки на покупку и продажу согласуются по "
           "телефону или в переписке, а сделка оформляется вручную. Из-за этого остатки на "
           "счетах депо и журнал сделок расходятся, а инвестор не может ответить на простой "
           "вопрос, сколько стоит его портфель сейчас. Когда одну и ту же операцию выполняют "
           "два сотрудника или клиент и сотрудник одновременно, данные теряются.")
    p(doc, "Целью работы является проектирование сетевой программной системы управления "
           "инвестициями и ценными бумагами банка, в которой клиенты и сотрудники работают с "
           "одними и теми же данными через общий сервер, а сделки исполняются согласованно и "
           "фиксируются в журнале.")
    p(doc, "Для достижения цели поставлены задачи:", first_line=0)
    for t in ("исследовать предметную область и определить, для кого и зачем создаётся система;",
              "выявить проблемы текущей работы и предложить мероприятия по их устранению;",
              "построить комплекс диаграмм UML, описывающих функции, структуру и поведение системы;",
              "получить программный код по модели и определить состояние реализации проекта."):
        bullet(doc, t)
    p(doc, "Объект исследования – деятельность банка по обслуживанию инвесторов и операциям с "
           "ценными бумагами; предмет – процессы учёта клиентов, портфелей, выпусков бумаг и "
           "сделок, а также способы их автоматизации в локальной сети банка.")
    p(doc, "Практическая значимость работы состоит в том, что спроектированная система уже "
           "реализована: веб-версия и оконное приложение работают с одной базой данных SQL Server, "
           "поэтому изменения, сделанные клиентом в браузере, сразу видны сотруднику в его окне.")
    page_break(doc)


def chapter1(doc):
    h1(doc, "ГЛАВА 1 ИССЛЕДОВАНИЕ ПРЕДМЕТНОЙ ОБЛАСТИ")

    h2(doc, "1.1 Описание предметной области")
    p(doc, "Банк выступает посредником между теми, кто выпускает ценные бумаги (эмитентами), и "
           "теми, кто вкладывает деньги (инвесторами). Чтобы инвестор мог купить бумагу, банк "
           "должен провести её по учёту: у каждой бумаги есть эмитент, вид (акция, облигация, "
           "депозитный сертификат), сегмент рынка, номинал и объём выпуска. Пока выпуск не "
           "зарегистрирован, торговать им нельзя, поэтому у бумаги есть статус: «Черновик», "
           "«На регистрации», «Зарегистрирован», «Размещён».")
    p(doc, "У каждого клиента открыт счёт депо, на котором числятся бумаги в определённом "
           "количестве. Когда клиент хочет продать часть бумаг, он выставляет предложение: "
           "какую бумагу, сколько штук и по какой цене он готов отдать. Другое лицо — клиент или "
           "сотрудник от имени клиента — может купить это предложение целиком или частично. "
           "Сделка исполняется сразу: бумаги переходят со счёта продавца на счёт покупателя, "
           "а в журнал пишутся две записи — покупка и продажа, каждая с комиссией банка.")
    p(doc, "С системой будут работать четыре группы пользователей, и для каждой из них она "
           "решает свою задачу:", first_line=0)
    for t in ("клиент – владелец счёта депо; ему нужно видеть свои бумаги, их стоимость и долю "
              "каждой бумаги в портфеле, покупать и продавать, а также задавать целевые доли, "
              "чтобы понимать, чего докупить;",
              "сотрудник – обслуживает клиентов: заводит новые организации и частных лиц, "
              "ставит бумаги на счёт, покупает от имени клиента, формирует отчёты;",
              "администратор – ведёт учётные записи сотрудников и клиентов, смотрит журнал "
              "действий и разбирает спорные операции;",
              "руководитель – ему нужен сводный отчёт за период: сколько операций исполнено, "
              "какой доход банк получил в виде комиссий и какие бумаги востребованы."):
        bullet(doc, t)
    p(doc, "Работа с ценными бумагами – это цепочка действий: выпуск заводится в справочнике и "
           "получает статус, бумаги зачисляются на счёт депо клиента, клиент выставляет "
           "предложение о продаже, покупатель его выкупает, сделка попадает в журнал, а цены "
           "бумаг периодически обновляются, чтобы стоимость портфеля была актуальной. "
           "Основные бизнес-процессы приведены в таблице 1.1.")
    caption(doc, "Таблица 1.1 – Основные бизнес-процессы")
    table(doc,
          ["№", "Процесс", "Кто выполняет", "Результат"],
          [["1", "Ведение клиентов и счетов депо", "Сотрудник", "Клиент и его счёт депо"],
           ["2", "Выпуск и регистрация бумаг", "Сотрудник", "Бумага со статусом «Размещён»"],
           ["3", "Зачисление бумаг на счёт", "Сотрудник", "Позиция в портфеле клиента"],
           ["4", "Выставление предложения о продаже", "Клиент", "Активное предложение на рынке"],
           ["5", "Покупка по предложению", "Клиент, сотрудник", "Сделка и две записи в журнале"],
           ["6", "Обновление цен и переоценка портфеля", "Система", "Актуальная стоимость активов"],
           ["7", "Отчёты и журнал действий", "Администратор, руководитель", "Утверждённый отчёт"]],
          [1.2, 5.2, 4.0, 5.4])
    p(doc, "Особое место занимает исполнение сделки. Простое «списать у одного и зачислить "
           "другому» здесь недостаточно: нужно одновременно проверить, что предложение ещё "
           "активно, что покупатель не покупает у самого себя, что на счёте продавца хватает "
           "бумаг, и только затем менять остатки. Если любая из проверок не пройдена, не должно "
           "измениться ничего. Поэтому исполнение сделки выполняется одной транзакцией на "
           "сервере базы данных — хранимой процедурой, а не набором отдельных запросов из "
           "клиентского приложения.")
    p(doc, "Таким образом, банк – организация с массовым обслуживанием инвесторов, участники "
           "которой нуждаются в общих данных о портфелях и сделках и в гарантии того, что "
           "одновременные операции не испортят учёт.")

